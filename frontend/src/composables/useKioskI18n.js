// 광고 화면으로 돌아갈 때 다음 고객을 위해 한국어로 초기화합니다.
export function resetKioskLocale() {
  locale.value = 'ko'
  localStorage.setItem('kiosk-locale', 'ko')
  document.documentElement.lang = 'ko'
}

// 언어 선택과 번역 함수를 모든 키오스크 화면에서 함께 사용하는 간단한 composable입니다.
export function useKioskI18n() {
  const currentLanguage = computed(
    () => KIOSK_LANGUAGES.find((item) => item.locale === locale.value) ?? KIOSK_LANGUAGES[0]
  )

  function setLocale(nextLocale) {
    if (!KIOSK_LANGUAGES.some((item) => item.locale === nextLocale)) return
    locale.value = nextLocale
    localStorage.setItem('kiosk-locale', nextLocale)
    document.documentElement.lang = nextLocale
  }

  function t(key) {
    return messages[locale.value]?.[key] ?? messages.ko[key] ?? key
  }

  function menuName(originalName) {
    if (locale.value === 'ko') return originalName
    return menuNames[locale.value]?.[originalName]
      ?? catalogProductNames[locale.value]?.[originalName]
      ?? originalName
  }

  function flavorName(originalName) {
    if (locale.value === 'ko') return originalName
    return flavorNames[locale.value]?.[originalName] ?? originalName
  }

  return { locale, currentLanguage, setLocale, t, menuName, flavorName }
}
