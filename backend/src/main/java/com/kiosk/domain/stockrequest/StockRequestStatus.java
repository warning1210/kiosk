package com.kiosk.domain.stockrequest;

/**
 * 재고 신청이 현재 어느 처리 단계에 있는지를 나타낸다.
 *
 * <p>DB에는 순서값이 아닌 상수 이름이 저장된다. 따라서 선언 순서는 업무 순서를 설명할 뿐, 상태 전환을
 * 자동으로 제한하지 않는다. 어떤 상태에서 다음 상태로 갈 수 있는지는 Service가 검사하고
 * {@link StockRequest}의 의도가 드러나는 메서드가 실제 값을 변경한다.
 */
public enum StockRequestStatus {
    /** 지점이 신청을 완료했고 본사의 판단을 기다리는 상태이다. */
    PENDING,

    /** 승인이 완료되었음을 표현하는 상태값이다. 현재 승인 기능은 곧바로 {@link #PREPARING}으로 이동한다. */
    APPROVED,

    /** 본사가 신청을 반려하여 더 이상 진행되지 않는 상태이다. */
    REJECTED,

    /** 본사가 승인한 상품을 출고하기 위해 준비하는 상태이다. */
    PREPARING,

    /** 배송 정보가 등록되어 상품이 지점으로 이동 중인 상태이다. */
    SHIPPING,

    /** 지점이 수령을 확인했고 재고 반영까지 끝난 상태이다. */
    DELIVERED,

    /** 처리가 종료된 상태이다. 현재 지점의 신청 취소 결과에 사용한다. */
    CLOSED
}
