package com.kiosk.domain.stockrequest;

/**
 * 지점이 재고 신청의 시급함을 본사에 전달할 때 사용하는 우선순위이다.
 *
 * <p>우선순위는 요청의 속성을 표현할 뿐, 이 enum 자체가 처리 순서를 정하거나 자동 승인하지는 않는다.
 */
public enum Urgency {
    /** 일반 요청보다 여유 있게 처리해도 되는 신청이다. */
    LOW,

    /** 별도 지정이 없을 때 사용하는 기본 긴급도이다. */
    NORMAL,

    /** 품절 위험 등으로 빠른 확인이 필요한 신청이다. */
    HIGH
}
