package com.kiosk.domain.inventory;

/**
 * 재고 수량이 변한 업무 원인을 구분한다.
 *
 * <p>같은 수량 증가·감소라도 원인이 다르면 운영자가 이력을 해석하는 방법이 달라진다. 이 값은 DB에
 * 문자열로 저장되므로 이름 변경 시 기존 데이터 마이그레이션이 필요하다.
 */
public enum InventoryTransactionType {
    /** 일반적인 입고로 재고가 증가했다. */
    IN,

    /** 일반적인 출고로 재고가 감소했다. */
    OUT,

    /** 실사나 관리자 판단에 따라 수량을 보정했다. */
    ADJUST,

    /** 고객 주문 처리로 재고가 감소했다. */
    ORDER,

    /** 재고 신청 상품의 수령 확인으로 재고가 증가했다. */
    REQUEST_RECEIVED,

    /** 파손·유통기한 만료 등의 폐기로 재고가 감소했다. */
    DISPOSAL
}
